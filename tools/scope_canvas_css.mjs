// One-time transform used when merging the canvas prototype: scopes its global
// stylesheet under .canvas-root so it cannot leak into the rest of the Studio.
//   node tools/scope_canvas_css.mjs <prototype index.css> canvas/canvas.css
import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';

const [src, out] = process.argv.slice(2);
const root = postcss.parse(readFileSync(src, 'utf8'));
const ROOT = '.canvas-root';

root.walkAtRules('media', (at) => {
  // The Studio shell is light-only; a dark canvas inside it would clash.
  if (at.params.includes('prefers-color-scheme: dark')) at.remove();
});
root.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  const scoped = rule.selectors.flatMap((sel) => {
    if (sel === 'html' || sel === 'body' || sel === '#root') return [];
    if (sel === ':root') return [ROOT];
    if (sel === '*') return [ROOT, `${ROOT} *`];
    if (sel === '.app' || sel.startsWith('.app ') || sel.startsWith('.app.')) return [ROOT + sel];
    return [`${ROOT} ${sel}`];
  });
  if (scoped.length === 0) rule.remove();
  else rule.selectors = scoped;
});
writeFileSync(out, '/* Generated by tools/scope_canvas_css.mjs from the canvas prototype stylesheet. */\n' + root.toString());
